#!/usr/bin/env bash
# Build the pinned libgit2 as static libraries into vendor/libgit2:
#   Libgit2.xcframework  device + simulator slices, linked into the app
#   macos/               host slice, for engine/native's host build and tests
# HTTPS goes through Security.framework (SecureTransport); no SSH yet.
# libgit2 is GPLv2 with the linking exception: it is linked unmodified.
set -euo pipefail
version="1.9.7"
sha256="1a4fbe7589e814777ae76b64734ad80f4ecad22cd33a22682a2aaea4ae5375e7"
root="$(cd "$(dirname "$0")/.." && pwd)"
dir="$root/vendor/libgit2"
tarball="$dir/libgit2-$version.tar.gz"
src="$dir/libgit2-$version"
# A pinned CMake from PyPI when none is installed; nothing lands on PATH.
if command -v cmake >/dev/null; then cmake=(cmake); else cmake=(uvx --from cmake==3.31.6 cmake); fi

mkdir -p "$dir"
if [ ! -f "$tarball" ]; then
  curl -fL --retry 3 -o "$tarball.part" "https://github.com/libgit2/libgit2/archive/refs/tags/v$version.tar.gz"
  mv "$tarball.part" "$tarball"
fi
echo "$sha256  $tarball" | shasum -a 256 -c -
rm -rf "$src" "$dir/build" && tar xzf "$tarball" -C "$dir"

# Node bundles llhttp too, and NodeMobile.framework exports it: linked into the
# app, libgit2's llhttp calls would bind to Node's copy (another version and
# layout) and every HTTP response reads as EOF. Prefix libgit2's copy instead.
rename="$dir/llhttp-prefix.h"
{
  echo "/* Generated by scripts/build-libgit2.sh: libgit2's bundled llhttp, renamed away from Node's. */"
  grep -ohE '\bllhttp_[a-z_]+\b|\bllhttp__internal_[a-z_0-9]+\b' "$src"/deps/llhttp/*.c "$src"/deps/llhttp/*.h \
    | sort -u | sed -E 's/.*/#define & dsh_git_&/'
} > "$rename"

# slice  sysroot  system-name
slices=(
  "ios-arm64 iphoneos iOS"
  "ios-arm64-simulator iphonesimulator iOS"
  "macos macosx Darwin"
)
for entry in "${slices[@]}"; do
  read -r slice sysroot system <<<"$entry"
  build="$dir/build/$slice"
  deployment=$([ "$system" = iOS ] && echo 16.0 || echo 13.0)
  "${cmake[@]}" -S "$src" -B "$build" -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_SYSTEM_NAME="$system" -DCMAKE_OSX_SYSROOT="$sysroot" -DCMAKE_OSX_ARCHITECTURES=arm64 \
    -DCMAKE_OSX_DEPLOYMENT_TARGET="$deployment" -DCMAKE_INSTALL_PREFIX="$dir/$slice" \
    -DCMAKE_C_FLAGS="-include $rename -fmacro-prefix-map=$src=libgit2" \
    -DBUILD_SHARED_LIBS=OFF -DBUILD_TESTS=OFF -DBUILD_CLI=OFF -DBUILD_EXAMPLES=OFF \
    -DUSE_HTTPS=SecureTransport -DUSE_SHA1=CollisionDetection -DUSE_SHA256=CommonCrypto \
    -DUSE_SSH=OFF -DUSE_GSSAPI=OFF -DUSE_NTLMCLIENT=OFF -DUSE_HTTP_PARSER=builtin \
    -DREGEX_BACKEND=builtin -DUSE_BUNDLED_ZLIB=OFF -DUSE_ICONV=ON >/dev/null
  "${cmake[@]}" --build "$build" --config Release -j "$(sysctl -n hw.ncpu)" >/dev/null
  "${cmake[@]}" --install "$build" >/dev/null
  if nm -gU "$dir/$slice/lib/libgit2.a" 2>/dev/null | grep -qE ' _llhttp'; then
    echo "libgit2 ($slice) still exports unprefixed llhttp symbols" >&2
    exit 1
  fi
done

rm -rf "$dir/Libgit2.xcframework"
xcodebuild -create-xcframework \
  -library "$dir/ios-arm64/lib/libgit2.a" -headers "$dir/ios-arm64/include" \
  -library "$dir/ios-arm64-simulator/lib/libgit2.a" -headers "$dir/ios-arm64-simulator/include" \
  -output "$dir/Libgit2.xcframework" >/dev/null
echo "libgit2 $version ready: $dir"
